// ---- 乱数 -------------------------------------------------------------------
// 同点の最善手からの選択や、ランダム手で使う乱数生成器(メルセンヌ・ツイスタ)。
// 引数なしで構築しているので、種は既定値 5489 に固定され、毎回同じ乱数列になる(結果の再現性のため)。
// 実行ごとに変えたいときは下のコメントアウトされた行(random_device で種を取る)を使う。
// `inline` 変数(C++17)にしてあるので、複数の .cpp から include されても実体は 1つになる。
